"""M2a parse spike — evaluate SEC Item-section extraction quality (P2).

Purpose: decide the filing text parse approach BEFORE building P3's chunker/index.
This script only MEASURES; it writes no application data.

For each investigable company's latest 10-K and 10-Q it records, per candidate
strategy, which Items were recovered and how much text each yielded, so the
choice is grounded in evidence rather than assumption.

Usage:
    python scripts/spike_parse_eval.py            # all 8 investigable issuers
    python scripts/spike_parse_eval.py NVDA AAPL  # subset
"""

from __future__ import annotations

import json
import os
import re
import sys
import traceback
from pathlib import Path

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "src"))

from dotenv import load_dotenv
load_dotenv(ROOT / ".env")

import psycopg2

DB_DSN = os.getenv(
    "DATABASE_URL_LOCAL_SYNC",
    "postgresql+psycopg2://exposure:exposure@localhost:5433/exposure_workbench",
).replace("postgresql+psycopg2://", "postgresql://")

OUT_MD = ROOT / "docs" / "spikes" / "M2_PARSE_EVAL.md"

# Items we care about for issuer research (10-K / 10-Q respectively).
KEY_ITEMS_10K = ["Item 1", "Item 1A", "Item 7", "Item 7A", "Item 8"]
KEY_ITEMS_10Q = ["Item 1", "Item 2", "Item 3", "Item 1A"]

_ITEM_RE = re.compile(r"^\s*item\s+(\d+[A-Za-z]?)\b", re.IGNORECASE | re.MULTILINE)


def companies(tickers: list[str] | None) -> list[tuple[str, str]]:
    with psycopg2.connect(DB_DSN) as conn, conn.cursor() as cur:
        if tickers:
            cur.execute("SELECT ticker, cik FROM companies WHERE ticker = ANY(%s) ORDER BY ticker", (tickers,))
        else:
            cur.execute("SELECT ticker, cik FROM companies WHERE is_investigable ORDER BY ticker")
        return [(t, c) for t, c in cur.fetchall()]


def strategy_edgar_obj(filing) -> tuple[dict[str, int], str]:
    """Strategy A: edgartools' typed filing object (filing.obj()) with .items."""
    obj = filing.obj()
    found: dict[str, int] = {}
    items = getattr(obj, "items", None)
    if not items:
        return found, "no .items attribute"
    for code in items:
        try:
            txt = obj[code]
        except Exception:
            txt = None
        if txt:
            found[str(code).strip()] = len(str(txt))
    return found, f"{len(items)} items advertised"


def strategy_text_regex(filing) -> tuple[dict[str, int], str]:
    """Strategy B: raw text + 'Item N' regex segmentation (source-agnostic fallback
    strategy — measured here only to compare, not to be used as a silent fallback)."""
    text = filing.text()
    if not text:
        return {}, "empty text"
    marks = [(m.group(1).upper(), m.start()) for m in _ITEM_RE.finditer(text)]
    found: dict[str, int] = {}
    for i, (code, start) in enumerate(marks):
        end = marks[i + 1][1] if i + 1 < len(marks) else len(text)
        key = f"Item {code}"
        found[key] = max(found.get(key, 0), end - start)
    return found, f"{len(text)} chars, {len(marks)} item marks"


def evaluate(tickers: list[str] | None) -> list[dict]:
    from edgar import Company, set_identity

    identity = os.environ.get("EDGAR_IDENTITY", "").strip()
    if not identity:
        raise SystemExit("EDGAR_IDENTITY not set")
    set_identity(identity)

    results: list[dict] = []
    for ticker, cik in companies(tickers):
        c = Company(int(cik))
        for form in ("10-K", "10-Q"):
            rec: dict = {"ticker": ticker, "form": form}
            try:
                filings = c.get_filings(form=form)
                if filings is None or len(filings) == 0:
                    rec["error"] = "no filings"
                    results.append(rec)
                    continue
                f = filings.latest(1)
                rec["accession"] = str(f.accession_no)
                rec["filing_date"] = str(f.filing_date)
                for label, fn in (("obj", strategy_edgar_obj), ("regex", strategy_text_regex)):
                    try:
                        found, note = fn(f)
                        rec[label] = {"items": found, "note": note}
                    except Exception as e:
                        rec[label] = {"items": {}, "note": f"FAILED {type(e).__name__}: {str(e)[:90]}"}
            except Exception as e:
                rec["error"] = f"{type(e).__name__}: {str(e)[:120]}"
                traceback.print_exc(limit=1)
            results.append(rec)
            print(f"  evaluated {ticker} {form}")
    return results


def render(results: list[dict]) -> str:
    lines = [
        "# M2a Parse Spike — SEC Item Extraction Evaluation",
        "",
        "Generated by `scripts/spike_parse_eval.py` (P2). Measures how well each",
        "candidate strategy recovers SEC Item sections from the latest 10-K/10-Q of",
        "every investigable issuer. **This decides the P3 chunker input.**",
        "",
        "Strategies compared:",
        "- **obj** — edgartools typed filing object (`filing.obj()` + `.items`)",
        "- **regex** — raw `filing.text()` segmented on `Item N` headings",
        "",
        "## Coverage of key items",
        "",
        "`Y` = section recovered with >500 chars, `small` = recovered but thin, `-` = missing.",
        "",
    ]
    for strat in ("obj", "regex"):
        lines += [f"### Strategy: {strat}", "", "| Ticker | Form | Key items recovered | Missing | Total items | Note |", "|---|---|---|---|---|---|"]
        for r in results:
            if "error" in r:
                lines.append(f"| {r['ticker']} | {r['form']} | — | — | — | ERROR {r['error']} |")
                continue
            data = r.get(strat, {})
            items = data.get("items", {})
            key = KEY_ITEMS_10K if r["form"] == "10-K" else KEY_ITEMS_10Q
            norm = { _norm(k): v for k, v in items.items() }
            got, missing = [], []
            for k in key:
                v = norm.get(_norm(k), 0)
                if v > 500:
                    got.append(f"{k}({v//1000}k)")
                elif v > 0:
                    got.append(f"{k}(small)")
                else:
                    missing.append(k)
            lines.append(
                f"| {r['ticker']} | {r['form']} | {', '.join(got) or '—'} | "
                f"{', '.join(missing) or 'none'} | {len(items)} | {data.get('note','')[:50]} |"
            )
        lines.append("")
    return "\n".join(lines)


def _norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


def main() -> None:
    tickers = sys.argv[1:] or None
    results = evaluate(tickers)
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(render(results))
    (OUT_MD.parent / "M2_PARSE_EVAL.json").write_text(json.dumps(results, indent=2, default=str))
    print(f"\nWrote {OUT_MD}")


if __name__ == "__main__":
    main()
