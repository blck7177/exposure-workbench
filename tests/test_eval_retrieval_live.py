"""V3-D1 — retrieval quality does not regress (live).

Run with:  pytest -m live -k eval_retrieval

There is no CI in this repository, so this is a test a human runs, not a merge
gate, and saying so plainly is better than describing a pipeline that does not
exist. Regenerate the reference with:

    python scripts/eval_retrieval.py --write-baseline
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

pytestmark = pytest.mark.live

ROOT = Path(__file__).resolve().parents[1]
BASELINE = ROOT / "docs" / "spikes" / "V3_RETRIEVAL_BASELINE.json"

# How far below the reference is a regression rather than noise. Retrieval here
# is deterministic given the same index and the same query — the embedding call
# is the only moving part — so the tolerance is for index drift, not sampling.
TOLERANCE = 0.10


def _baseline() -> dict:
    if not BASELINE.exists():
        pytest.skip("no baseline recorded; run scripts/eval_retrieval.py --write-baseline")
    return json.loads(BASELINE.read_text())


async def test_precision_has_not_fallen_below_the_recorded_baseline():
    """precision@k, not recall@k, is what this guards. recall@5 measured 1.000
    on all 24 queries when the baseline was taken — which does not mean
    retrieval is perfect, it means "did ANY of the top five land in the right SEC
    item" is too easy a question on a corpus where seven of every ten returned
    passages already do. A saturated metric cannot detect a regression."""
    from scripts.eval_retrieval import evaluate

    ref = _baseline()
    now = await evaluate()

    assert now["scored"] >= ref["scored"] * 0.9, (
        f"fewer queries scored than at baseline ({now['scored']} vs {ref['scored']}): "
        f"skipped {now['skipped']}"
    )
    for metric in ("precision_at_5", "precision_at_10"):
        assert now[metric] >= ref[metric] - TOLERANCE, (
            f"{metric} {now[metric]} is more than {TOLERANCE} below the "
            f"baseline {ref[metric]}"
        )


async def test_retrieval_still_finds_the_right_section_at_all():
    """The floor check recall@5 is kept for: it cannot detect degradation, but it
    would catch retrieval breaking outright — a wrong embedding model, an empty
    index, a filter that excludes everything."""
    from scripts.eval_retrieval import evaluate

    now = await evaluate()
    assert now["recall_at_5"] >= 0.8, f"retrieval is missing the right item entirely: {now}"


def test_the_golden_set_is_not_anchored_on_chunk_ids():
    """Chunk ids are regenerated by every re-ingest, so a set anchored on them
    measures nothing the day after it is written. The labels are SEC item codes
    precisely because those survive re-indexing and chunker-constant changes."""
    text = (ROOT / "data" / "eval" / "retrieval_golden.yaml").read_text()
    assert "chunk_" not in text
    assert "expect_items" in text
